CREATE DATABASE IF NOT EXISTS web_ban_sach
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE web_ban_sach;

-- 1. KHACHHANG
CREATE TABLE KHACHHANG (
    MaKH BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    SDT VARCHAR(15) NULL,
    GioiTinh BIT(1) NULL COMMENT '1 = Nam, 0 = Nu',
    AnhDaiDien VARCHAR(500) NULL,
    NgaySinh DATE NULL,
    CONSTRAINT UQ_KHACHHANG_SDT UNIQUE (SDT),
    CONSTRAINT CK_KHACHHANG_GIOITINH
        CHECK (GioiTinh IS NULL OR GioiTinh IN (b'0', b'1'))
) ENGINE=InnoDB;

-- 2. TAIKHOAN (FK MaKH -> KHACHHANG theo ERD)
CREATE TABLE TAIKHOAN (
    MaTK BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaKH BIGINT UNSIGNED NULL,
    Email VARCHAR(150) NOT NULL,
    TenDN VARCHAR(50) NULL,
    MatKhau VARCHAR(255) NULL,
    PTDangNhap ENUM('LOCAL', 'GOOGLE', 'FACEBOOK') NOT NULL DEFAULT 'LOCAL',
    VaiTro ENUM('KHACH_HANG', 'ADMIN') NOT NULL DEFAULT 'KHACH_HANG',
    TrangThai ENUM('HOAT_DONG', 'KHOA') NOT NULL DEFAULT 'HOAT_DONG',
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NgayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT UQ_TAIKHOAN_EMAIL UNIQUE (Email),
    CONSTRAINT UQ_TAIKHOAN_TENDN UNIQUE (TenDN),
    CONSTRAINT FK_TAIKHOAN_KHACHHANG
        FOREIGN KEY (MaKH) REFERENCES KHACHHANG(MaKH)
        ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

-- 3. DIACHI
CREATE TABLE DIACHI (
    MaDiaChi BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaKH BIGINT UNSIGNED NOT NULL,
    HoTenNguoiNhan VARCHAR(100) NOT NULL,
    SDTNguoiNhan VARCHAR(15) NOT NULL,
    DiaChiNhan VARCHAR(500) NOT NULL,
    MacDinh BOOLEAN NOT NULL DEFAULT FALSE,
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_DIACHI_KHACHHANG
        FOREIGN KEY (MaKH) REFERENCES KHACHHANG(MaKH)
        ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

-- 4. LOAISACH
CREATE TABLE LOAISACH (
    MaLoai BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    TenLoai VARCHAR(100) NOT NULL,
    HinhAnh VARCHAR(500) NULL,
    TrangThai ENUM('HOAT_DONG', 'NGUNG') NOT NULL DEFAULT 'HOAT_DONG',
    MoTa TEXT NULL,
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NgayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT UQ_LOAISACH_TEN UNIQUE (TenLoai)
) ENGINE=InnoDB;

-- 5. SACH
CREATE TABLE SACH (
    MaSach BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaLoai BIGINT UNSIGNED NOT NULL,
    TenSach VARCHAR(255) NOT NULL,
    TacGia VARCHAR(255) NOT NULL,
    ISBN VARCHAR(20) NULL,
    SoLuong INT UNSIGNED NOT NULL DEFAULT 0,
    MoTa TEXT NULL,
    GiaBan DECIMAL(15,2) UNSIGNED NOT NULL,
    HinhAnh VARCHAR(500) NULL,
    NXB VARCHAR(255) NULL,
    NamXB SMALLINT UNSIGNED NULL,
    SoTrang SMALLINT UNSIGNED NULL,
    TrangThai ENUM('DANG_BAN', 'HET_HANG', 'NGUNG_BAN')
        NOT NULL DEFAULT 'DANG_BAN',
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NgayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT UQ_SACH_ISBN UNIQUE (ISBN),
    CONSTRAINT FK_SACH_LOAISACH
        FOREIGN KEY (MaLoai) REFERENCES LOAISACH(MaLoai)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    INDEX IDX_SACH_TENSACH (TenSach),
    INDEX IDX_SACH_LOAI (MaLoai)
) ENGINE=InnoDB;

-- 6. GIOHANG
CREATE TABLE GIOHANG (
    MaGioHang BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaKH BIGINT UNSIGNED NOT NULL,
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NgayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT UQ_GIOHANG_MAKH UNIQUE (MaKH),
    CONSTRAINT FK_GIOHANG_KHACHHANG
        FOREIGN KEY (MaKH) REFERENCES KHACHHANG(MaKH)
        ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

-- 7. CHITIETGIOHANG
CREATE TABLE CHITIETGIOHANG (
    MaGioHang BIGINT UNSIGNED NOT NULL,
    MaSach BIGINT UNSIGNED NOT NULL,
    SoLuong INT UNSIGNED NOT NULL,
    DonGia DECIMAL(15,2) UNSIGNED NOT NULL,
    PRIMARY KEY (MaGioHang, MaSach),
    CONSTRAINT FK_CTGIOHANG_GIOHANG
        FOREIGN KEY (MaGioHang) REFERENCES GIOHANG(MaGioHang)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_CTGIOHANG_SACH
        FOREIGN KEY (MaSach) REFERENCES SACH(MaSach)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT CK_CTGIOHANG_SOLUONG CHECK (SoLuong > 0)
) ENGINE=InnoDB;

-- 8. MAGIAMGIA
CREATE TABLE MAGIAMGIA (
    MaGiamGia BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaCode VARCHAR(50) NOT NULL,
    TenChuongTrinh VARCHAR(100) NOT NULL,
    PhanTramGiam DECIMAL(5,2) NULL,
    SoTienGiamToiDa DECIMAL(15,2) UNSIGNED NULL,
    GiaTriDonToiThieu DECIMAL(15,2) UNSIGNED NOT NULL DEFAULT 0,
    NgayBatDau DATETIME NOT NULL,
    NgayKetThuc DATETIME NOT NULL,
    SoLuong INT UNSIGNED NOT NULL DEFAULT 0,
    TrangThai ENUM('HOAT_DONG', 'NGUNG') NOT NULL DEFAULT 'HOAT_DONG',
    CONSTRAINT UQ_MAGIAMGIA_MACODE UNIQUE (MaCode),
    CONSTRAINT CK_MAGIAMGIA_PHANTRAM
        CHECK (PhanTramGiam IS NULL OR
               (PhanTramGiam > 0 AND PhanTramGiam <= 100)),
    CONSTRAINT CK_MAGIAMGIA_THOIGIAN CHECK (NgayKetThuc > NgayBatDau)
) ENGINE=InnoDB;

-- 9. DONHANG
CREATE TABLE DONHANG (
    MaDH BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaKH BIGINT UNSIGNED NOT NULL,
    MaGiamGia BIGINT UNSIGNED NULL,
    NgayDat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    GiaTamTinh DECIMAL(15,2) UNSIGNED NOT NULL DEFAULT 0,
    GiamGia DECIMAL(15,2) UNSIGNED NOT NULL DEFAULT 0,
    PhiVC DECIMAL(15,2) UNSIGNED NOT NULL DEFAULT 0,
    TongTien DECIMAL(15,2) UNSIGNED NOT NULL DEFAULT 0,
    TrangThai ENUM(
        'CHO_XAC_NHAN', 'DA_XAC_NHAN', 'DANG_GIAO', 'DA_GIAO', 'DA_HUY'
    ) NOT NULL DEFAULT 'CHO_XAC_NHAN',
    GhiChu TEXT NULL,
    NgayCapNhat DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    ThoiGianHetHanTT DATETIME NULL,
    CONSTRAINT FK_DONHANG_KHACHHANG
        FOREIGN KEY (MaKH) REFERENCES KHACHHANG(MaKH)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_DONHANG_MAGIAMGIA
        FOREIGN KEY (MaGiamGia) REFERENCES MAGIAMGIA(MaGiamGia)
        ON UPDATE CASCADE ON DELETE SET NULL,
    INDEX IDX_DONHANG_KH (MaKH),
    INDEX IDX_DONHANG_TRANGTHAI (TrangThai),
    INDEX IDX_DONHANG_NGAYDAT (NgayDat)
) ENGINE=InnoDB;

-- 10. CHITIETDONHANG
CREATE TABLE CHITIETDONHANG (
    MaDH BIGINT UNSIGNED NOT NULL,
    MaSach BIGINT UNSIGNED NOT NULL,
    SoLuong INT UNSIGNED NOT NULL,
    DonGia DECIMAL(15,2) UNSIGNED NOT NULL,
    PRIMARY KEY (MaDH, MaSach),
    CONSTRAINT FK_CTDONHANG_DONHANG
        FOREIGN KEY (MaDH) REFERENCES DONHANG(MaDH)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_CTDONHANG_SACH
        FOREIGN KEY (MaSach) REFERENCES SACH(MaSach)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT CK_CTDONHANG_SOLUONG CHECK (SoLuong > 0),
    INDEX IDX_CTDONHANG_SACH (MaSach)
) ENGINE=InnoDB;

-- 11. PTTHANHTOAN
CREATE TABLE PTTHANHTOAN (
    MaPTTT BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    TenPTTT VARCHAR(50) NOT NULL,
    MoTa TEXT NULL,
    TrangThai ENUM('HOAT_DONG', 'NGUNG') NOT NULL DEFAULT 'HOAT_DONG',
    CONSTRAINT UQ_PTTT_TEN UNIQUE (TenPTTT)
) ENGINE=InnoDB;

-- 12. THANHTOAN
CREATE TABLE THANHTOAN (
    MaThanhToan BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    MaPTTT BIGINT UNSIGNED NOT NULL,
    MaDH BIGINT UNSIGNED NOT NULL,
    SoTien DECIMAL(15,2) UNSIGNED NOT NULL,
    MaGiaoDich VARCHAR(150) NULL,
    ThoiGianTT DATETIME NULL,
    TrangThai ENUM(
        'CHO_THANH_TOAN', 'THANH_CONG', 'THAT_BAI', 'DA_HOAN_TIEN'
    ) NOT NULL DEFAULT 'CHO_THANH_TOAN',
    NoiDung TEXT NULL,
    CONSTRAINT FK_THANHTOAN_DONHANG
        FOREIGN KEY (MaDH) REFERENCES DONHANG(MaDH)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT FK_THANHTOAN_PTTT
        FOREIGN KEY (MaPTTT) REFERENCES PTTHANHTOAN(MaPTTT)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    INDEX IDX_THANHTOAN_DONHANG (MaDH),
    INDEX IDX_THANHTOAN_MAGIAODICH (MaGiaoDich)
    
) ENGINE=InnoDB;

-- 13. DANHGIA (FK kep (MaDH, MaSach) -> CHITIETDONHANG theo ERD)
CREATE TABLE DANHGIA (
    MaDanhGia BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    SoSao TINYINT UNSIGNED NOT NULL,
    NoiDung TEXT NULL,
    NgayDanhGia DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TrangThai ENUM('HIEN_THI', 'AN') NOT NULL DEFAULT 'HIEN_THI',
    MaDH BIGINT UNSIGNED NOT NULL,
    MaSach BIGINT UNSIGNED NOT NULL,
    CONSTRAINT UQ_DANHGIA_DH_SACH UNIQUE (MaDH, MaSach),
    CONSTRAINT FK_DANHGIA_CTDONHANG
        FOREIGN KEY (MaDH, MaSach) REFERENCES CHITIETDONHANG(MaDH, MaSach)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT CK_DANHGIA_SOSAO CHECK (SoSao BETWEEN 1 AND 5),
    INDEX IDX_DANHGIA_SACH (MaSach)
) ENGINE=InnoDB;

-- 14. KH_MGG (Ví mã giảm giá đã lưu của từng khách hàng theo ERD)
CREATE TABLE KH_MGG (
    MaGiamGia BIGINT UNSIGNED NOT NULL,
    MaKH BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (MaGiamGia, MaKH),
    CONSTRAINT FK_KHMGG_MAGIAMGIA
        FOREIGN KEY (MaGiamGia) REFERENCES MAGIAMGIA(MaGiamGia)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT FK_KHMGG_KHACHHANG
        FOREIGN KEY (MaKH) REFERENCES KHACHHANG(MaKH)
        ON UPDATE CASCADE ON DELETE CASCADE,
    INDEX IDX_KHMGG_KH (MaKH)
) ENGINE=InnoDB;

